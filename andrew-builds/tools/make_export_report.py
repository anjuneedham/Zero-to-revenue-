#!/usr/bin/env python3
"""Builds EPISODE_00N_EXPORT_REPORT.md from production-reports/qa_*.json and build_*.json (what was checked, what passed, what is still not final)."""
import json
import os
import re
from pathlib import Path

EP = Path(os.environ.get("EPISODE_DIR", Path(__file__).resolve().parents[1] / "episode-001"))
N = re.search(r"(\d+)$", EP.name).group(1)
rep = EP / "production-reports"
rows, details = [], []
for q in sorted(rep.glob("qa_*.json")):
    d = json.loads(q.read_text())
    b = json.loads((rep / ("build_" + re.sub(r"_PROOF$", "", q.stem[3:]) + ".json")).read_text()) if (rep / ("build_" + re.sub(r"_PROOF$", "", q.stem[3:]) + ".json")).exists() else {}
    passed = sum(1 for c in d["checks"] if c["result"] == "PASS")
    rows.append(f"| `{Path(d['file']).name}` | {d['kind']} | {int(d['duration_s'] // 60)}:{int(d['duration_s'] % 60):02} | {passed}/{len(d['checks'])} | **{d['verdict']}** |")
    why = "\n".join(f"  - {w}" for w in d["not_final_because"]) or "  - (nothing: all gates met)"
    chk = "\n".join(f"| {c['check']} | {c['result']} | {c['detail']} |" for c in d["checks"])
    gaps = ", ".join(b.get("missing_clips", [])) or "none"
    nar = "; ".join(b.get("narration_not_final", [])) or "all real"
    unconf = "; ".join(b.get("overlays_skipped_unconfirmed", [])) or "none"
    details.append(f"""### {Path(d['file']).name}
- Contact sheet (24 evenly spaced frames, for visual review): `{d['contact_sheet']}`
- Footage gaps rendered as slates: {gaps}
- Narration not final: {nar}
- Overlays held back until confirmed: {unconf}
- Captions: `{b.get('captions', '?')}` ({b.get('captions_timing', '')})
- Why NOT FINAL:
{why}

| Automated check | Result | Detail |
|---|---|---|
{chk}
""")
(EP / f"EPISODE_{N}_EXPORT_REPORT.md").write_text(f"""# EPISODE {N}: EXPORT REPORT

*Generated by `tools/make_export_report.py` from the QA and build JSON.*

## Read this first
Every file below is an **assembly proof**, not a finished video: narration is a robot guide track (or silence), some footage is a visible FOOTAGE NEEDED slate, script placeholders are unresolved, and every frame carries an ASSEMBLY PROOF watermark. They exist to prove the pipeline end to end and to let you judge pacing. **Do not publish any of them.**
No export is marked READY FOR REVIEW because none can yet meet the gates (real narration, all footage, no placeholders).

## Summary
| File | Kind | Length | Automated checks | Verdict |
|---|---|---|---|---|
{chr(10).join(rows)}

## What automation can and cannot tell you
Passing means: correct size/aspect/fps/codecs, audio present at the target loudness without clipping, no long silence or blank frames, valid and readable caption file. It does **not** mean the video is good, accurate, or safe to publish. The human-review list for each file is in its `qa_*.json`:
1. Watch it once with sound. 2. Read every frame with a screen recording for private information. 3. Confirm every spoken claim is true on the publishing day. 4. Check caption timing against the real narration. 5. Check any music never masks the voice.

## Details
{chr(10).join(details)}
## How to reproduce
```
python3 andrew-builds/tools/produce.py episode --scratch-vo   # or without --scratch-vo once VO_*.wav exist
python3 andrew-builds/tools/qa.py video andrew-builds/episode-{N}/exports/<file> --kind long --srt andrew-builds/episode-{N}/captions/<file>.srt
python3 andrew-builds/tools/make_export_report.py
```
""")
print("wrote", f"EPISODE_{N}_EXPORT_REPORT.md")
