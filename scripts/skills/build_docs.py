#!/usr/bin/env python3
"""Regenerate ATTRIBUTION.md and docs/skills-registry.md from docs/skills-manifest.json + scripts/skills/skills_meta.py.

    python3 scripts/skills/build_docs.py
"""
import json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import frontmatter  # noqa: E402
from skills_meta import CATEGORY_LABEL, GOAL_LABEL, META  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SKILLS = ROOT / ".claude" / "skills"
MANIFEST = ROOT / "docs" / "skills-manifest.json"
CUSTOM = ["agriloop-growth", "buildflow-growth", "fashion-launch", "trading-lab", "investing-plan", "hormozi-lens"]
ORDER = ["saas", "eng", "fashion", "trading", "invest", "sales", "docs"]


def esc(s):
    return s.replace("|", "\\|")


def main():
    manifest = json.loads(MANIFEST.read_text())
    manifest.sort(key=lambda e: (ORDER.index(e["category"]), e["name"]))

    # ---- ATTRIBUTION.md
    lines = [
        "# Attribution for vendored Agent Skills",
        "",
        "The folders in `.claude/skills/` listed below were copied **unmodified** from open-source repositories, pinned to the",
        "commit hash shown. Each folder keeps its own `LICENSE` file (if the skill had none, the upstream repository's root",
        "licence was copied next to it). Only MIT, Apache-2.0, BSD and CC-BY sources are allowed. Custom skills are listed",
        "at the bottom and are original to this repository.",
        "",
        "Generated by `scripts/skills/build_docs.py` from `docs/skills-manifest.json`. Do not edit by hand.",
        "",
        "| # | Skill | Source (pinned) | Commit | License | Installed |",
        "|---|---|---|---|---|---|",
    ]
    for i, e in enumerate(manifest, 1):
        lines.append(
            f"| {i} | `{e['name']}` | [{e['repo']}]({e['source_url']}) | `{e['commit']}` | {e['license']} | {e['installed']} |"
        )
    lines += ["", "## Source repositories", "", "| Repository | Commit | Skills | License |", "|---|---|---|---|"]
    by_repo = {}
    for e in manifest:
        by_repo.setdefault((e["repo"], e["commit"], e["license"]), []).append(e["name"])
    for (repo, commit, lic), names in sorted(by_repo.items()):
        lines.append(f"| [{repo}](https://github.com/{repo}/tree/{commit}) | `{commit}` | {len(names)} | {lic} |")
    lines += [
        "",
        "## Notes on licences",
        "",
        "- Anthropic's `anthropics/skills` repository mixes licences: skills with an Apache-2.0 `LICENSE.txt` (e.g. `frontend-design`,",
        "  `skill-creator`) are vendored; its `docx`, `pdf`, `pptx` and `xlsx` skills are proprietary and were **rejected**.",
        "- `pdf` comes from `openai/skills`, which has no root licence file but ships an Apache-2.0 `LICENSE.txt` inside the skill.",
        "- Skills with per-skill notes (caution flags) are listed in `docs/skills-manifest.json` under `notes`.",
        "",
        "## Custom skills (original, this repository)",
        "",
    ]
    for n in CUSTOM:
        lines.append(f"- `{n}`: {META[n][0]}")
    (ROOT / "ATTRIBUTION.md").write_text("\n".join(lines) + "\n")

    # ---- docs/skills-registry.md
    r = [
        "# Skills registry",
        "",
        "Every skill in `.claude/skills/` (70 vendored open-source + 6 custom). Check this list before starting a task.",
        "Generated by `scripts/skills/build_docs.py`; edit `scripts/skills/skills_meta.py` and the manifest, not this file.",
        "Provenance, licences and pinned commits: [`ATTRIBUTION.md`](../ATTRIBUTION.md). Vetting method and rejected list:",
        "[`docs/skills-vetting.md`](skills-vetting.md).",
        "",
        "| Skill | Category | Goal served | Purpose | Trigger (example) | Source | License |",
        "|---|---|---|---|---|---|---|",
    ]
    for e in manifest:
        purpose, trig = META[e["name"]]
        fm, _ = frontmatter.read(SKILLS / e["name"] / "SKILL.md")
        caution = " **(see caution)**" if e.get("notes") else ""
        r.append(
            f"| `{e['name']}` | {CATEGORY_LABEL[e['category']]} | {GOAL_LABEL[e['category']]} | {esc(purpose)}{caution} | {esc(trig)} | "
            f"[{e['repo']}]({e['source_url']}) @ `{e['commit'][:9]}` | {e['license']} |"
        )
    for n in CUSTOM:
        purpose, trig = META[n]
        r.append(f"| `{n}` | Custom | {GOAL_LABEL['custom']} | {esc(purpose)} | {esc(trig)} | This repo (original) | n/a |")
    r += ["", "## Cautions (skills whose docs mention optional external tools or special requirements)", ""]
    for e in manifest:
        if e.get("notes"):
            r.append(f"- `{e['name']}`: {e['notes']}")
    (ROOT / "docs" / "skills-registry.md").write_text("\n".join(r) + "\n")
    print(f"wrote ATTRIBUTION.md ({len(manifest)} vendored) and docs/skills-registry.md ({len(manifest)+len(CUSTOM)} rows)")


if __name__ == "__main__":
    main()
